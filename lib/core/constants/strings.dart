extension LocalizedString on String {
  String tr(String langCode) {
    if (langCode == 'en') {
      // In a real app we would use AppStrings reflection/map, but this is a simplified hardcoded mapping for Demo
      return _enTranslations[this] ?? this;
    }
    return this; // Assume TR text is default key
  }
}

